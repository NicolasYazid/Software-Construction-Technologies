using System;
using System.Globalization;

namespace GinRummy.Domain.Entities.Authentication
{
    /// <summary>
    /// Whoever an access token was granted to: a player with an account or a guest. Exactly one of the two
    /// identifiers has a value, so an account and a guest are never mixed in a single number. Two owners are
    /// equal when they are of the same kind and have the same identifier.
    /// </summary>
    public sealed class AccessTokenOwner : IEquatable<AccessTokenOwner>
    {
        private const int HashMultiplier = 397;

        private AccessTokenOwner(int? playerAccountId, int? guestSessionId)
        {
            PlayerAccountId = playerAccountId;
            GuestSessionId = guestSessionId;
        }

        /// <summary>
        /// Gets the identifier of the account when a player holds the token. Null when a guest holds it.
        /// </summary>
        public int? PlayerAccountId { get; private set; }

        /// <summary>
        /// Gets the identifier of the guest session when a guest holds the token. Null when a player holds it.
        /// </summary>
        public int? GuestSessionId { get; private set; }

        /// <summary>
        /// Gets a value indicating whether a guest holds the token.
        /// </summary>
        public bool IsGuest
        {
            get { return GuestSessionId.HasValue; }
        }

        /// <summary>
        /// Creates the owner that is a player with an account.
        /// </summary>
        /// <param name="playerAccountId">Identifier of the account; must be positive.</param>
        /// <returns>The owner.</returns>
        public static AccessTokenOwner OfPlayerAccount(int playerAccountId)
        {
            ValidateIdentifier(playerAccountId, nameof(playerAccountId));

            return new AccessTokenOwner(playerAccountId, null);
        }

        /// <summary>
        /// Creates the owner that is a guest.
        /// </summary>
        /// <param name="guestSessionId">Identifier of the guest session; must be positive.</param>
        /// <returns>The owner.</returns>
        public static AccessTokenOwner OfGuestSession(int guestSessionId)
        {
            ValidateIdentifier(guestSessionId, nameof(guestSessionId));

            return new AccessTokenOwner(null, guestSessionId);
        }

        /// <summary>
        /// Tells whether another owner is of the same kind and has the same identifier.
        /// </summary>
        /// <param name="other">Owner to compare with.</param>
        /// <returns>True when both are the same owner.</returns>
        public bool Equals(AccessTokenOwner other)
        {
            bool isSameOwner = (other != null)
                && (PlayerAccountId == other.PlayerAccountId)
                && (GuestSessionId == other.GuestSessionId);

            return isSameOwner;
        }

        /// <summary>
        /// Tells whether an object is the same owner.
        /// </summary>
        /// <param name="obj">Object to compare with.</param>
        /// <returns>True when the object is an owner of the same kind with the same identifier.</returns>
        public override bool Equals(object obj)
        {
            return Equals(obj as AccessTokenOwner);
        }

        /// <summary>
        /// Gets a hash code that agrees with the equality of the owners.
        /// </summary>
        /// <returns>The hash code.</returns>
        public override int GetHashCode()
        {
            unchecked
            {
                return (PlayerAccountId.GetValueOrDefault() * HashMultiplier) ^ GuestSessionId.GetValueOrDefault();
            }
        }

        /// <summary>
        /// Gets a text that tells the kind of the owner and its identifier, for the logs.
        /// </summary>
        /// <returns>The text.</returns>
        public override string ToString()
        {
            string kind = IsGuest ? "GuestSession" : "PlayerAccount";
            int identifier = IsGuest ? GuestSessionId.Value : PlayerAccountId.Value;

            return string.Format(CultureInfo.InvariantCulture, "{0} {1}", kind, identifier);
        }

        // Both kinds of identifier are generated by the database, so they start at one.
        private static void ValidateIdentifier(int identifier, string parameterName)
        {
            if (identifier <= 0)
            {
                throw new ArgumentException("The identifier must be positive.", parameterName);
            }
        }
    }
}
